const test = require("node:test");
const assert = require("node:assert/strict");

const {
  describeStatement,
  computeSchemaFingerprint,
  isTransientDbError,
  extractSchemaManifest,
  diffSchema,
} = require("../src/migrations/schemaTools");

test("describeStatement da una etiqueta estable y legible a cada sentencia", () => {
  assert.equal(describeStatement("CREATE TABLE IF NOT EXISTS users (id UUID PRIMARY KEY)"), "table:users");
  assert.equal(
    describeStatement("ALTER TABLE customers ADD COLUMN IF NOT EXISTS notes TEXT;"),
    "column:customers.notes"
  );
  assert.equal(describeStatement("CREATE UNIQUE INDEX IF NOT EXISTS idx_x ON t(LOWER(name));"), "index:idx_x");
  assert.equal(describeStatement("DROP TRIGGER IF EXISTS trg_a ON users;"), "drop-trigger:trg_a");
  assert.equal(describeStatement("CREATE TRIGGER trg_a\n BEFORE UPDATE ON users"), "trigger:trg_a");
  assert.equal(describeStatement("CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger"), "function:set_updated_at");
  assert.equal(describeStatement("INSERT INTO system_config (key, value) VALUES ('a','b')"), "seed:system_config");
  assert.equal(describeStatement("UPDATE products p SET stock_qty = 1"), "data:products");
  assert.equal(
    describeStatement("DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_a') THEN ALTER TABLE t ADD CONSTRAINT fk_a FOREIGN KEY (x) REFERENCES y(id); END IF; END $$;"),
    "constraint:fk_a"
  );
  assert.equal(describeStatement("SET LOCAL search_path TO public;"), "session");
});

test("la huella del esquema cambia con cualquier sentencia y es estable", () => {
  const a = computeSchemaFingerprint(["CREATE TABLE IF NOT EXISTS a (id int);"]);
  const b = computeSchemaFingerprint(["CREATE TABLE IF NOT EXISTS a (id int);"]);
  const c = computeSchemaFingerprint(["CREATE TABLE IF NOT EXISTS a (id bigint);"]);
  assert.equal(a, b);
  assert.notEqual(a, c);
  assert.match(a, /^[0-9a-f]{64}$/);
});

test("isTransientDbError reconoce timeouts, bloqueos y caídas de conexión", () => {
  for (const code of ["55P03", "57014", "40P01", "40001", "08006", "08003", "53300", "57P01"]) {
    assert.equal(isTransientDbError(code), true, code);
  }
  for (const code of ["42501", "23505", "42P01", "XX000", undefined]) {
    assert.equal(isTransientDbError(code), false, String(code));
  }
});

const SAMPLE = [
  `CREATE TABLE IF NOT EXISTS users (
      id UUID PRIMARY KEY,
      email TEXT NOT NULL UNIQUE,
      role TEXT NOT NULL DEFAULT 'STAFF' CHECK (role IN ('SUPERADMIN','ADMIN','STAFF')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );`,
  `CREATE TABLE IF NOT EXISTS orders (
      id UUID PRIMARY KEY,
      order_no BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
      customer_id UUID NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
      status TEXT NOT NULL DEFAULT 'DELIVERED'
        CHECK (status IN ('A','B')),
      CONSTRAINT orders_range_chk CHECK (id IS NOT NULL)
    );`,
  `ALTER TABLE users ADD COLUMN IF NOT EXISTS session_version INT NOT NULL DEFAULT 0;`,
  `ALTER TABLE recipes ADD COLUMN IF NOT EXISTS cost_mode VARCHAR(10) NOT NULL DEFAULT 'INSUMOS' CHECK (cost_mode IN ('INSUMOS','MANUAL'));`,
  `CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);`,
  `CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);`,
  `DO $$ BEGIN IF EXISTS (SELECT 1) THEN DROP INDEX IF EXISTS idx_users_email; END IF; END $$;`,
  `CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$ BEGIN NEW.updated_at = NOW(); RETURN NEW; END; $$ LANGUAGE plpgsql;`,
  `DROP TRIGGER IF EXISTS trg_users_updated_at ON users;`,
  `CREATE TRIGGER trg_users_updated_at
      BEFORE UPDATE ON users
      FOR EACH ROW EXECUTE PROCEDURE set_updated_at();`,
  `DO $$
    BEGIN
      IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'orders_status_check_v2') THEN
        ALTER TABLE orders ADD CONSTRAINT orders_status_check_v2
          CHECK (status IN ('A','B','C'));
      END IF;
      ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_status_check;
    EXCEPTION WHEN undefined_table THEN NULL;
    END $$;`,
  `DO $$
    BEGIN
      IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'order_items_variant_id_fkey') THEN
        ALTER TABLE order_items ADD CONSTRAINT order_items_variant_id_fkey
          FOREIGN KEY (variant_id) REFERENCES product_variants(id) ON DELETE SET NULL;
      END IF;
    END $$;`,
  `ALTER TABLE products VALIDATE CONSTRAINT products_cost_price_clp_check;`,
  `INSERT INTO system_config (key, value) VALUES ('cake_base_price', '30000') ON CONFLICT (key) DO NOTHING;`,
];

test("extractSchemaManifest deduce tablas, columnas e índices", () => {
  const m = extractSchemaManifest(SAMPLE);
  assert.deepEqual([...m.tables.get("users")].sort(), ["created_at", "email", "id", "role", "session_version"]);
  assert.deepEqual([...m.tables.get("orders")].sort(), ["customer_id", "id", "order_no", "status"]);
  assert.deepEqual([...m.tables.get("recipes")], ["cost_mode"]);
  assert.equal(m.indexes.has("idx_users_role"), true);
  assert.equal(m.indexes.has("idx_users_email"), false, "el DROP INDEX posterior lo quita");
  assert.equal(m.functions.has("set_updated_at"), true);
  assert.deepEqual(m.triggers.get("trg_users_updated_at"), { table: "users" });
});

test("extractSchemaManifest predice los nombres de restricciones que genera PostgreSQL", () => {
  const m = extractSchemaManifest(SAMPLE);
  const c = (name) => m.constraints.get(name);
  assert.deepEqual(c("users_pkey"), { table: "users", type: "p" });
  assert.deepEqual(c("users_email_key"), { table: "users", type: "u" });
  assert.deepEqual(c("users_role_check"), { table: "users", type: "c" });
  assert.deepEqual(c("orders_order_no_key"), { table: "orders", type: "u" });
  assert.deepEqual(c("orders_customer_id_fkey"), { table: "orders", type: "f" });
  assert.deepEqual(c("orders_range_chk"), { table: "orders", type: "c" });
  assert.deepEqual(c("recipes_cost_mode_check"), { table: "recipes", type: "c" });
  assert.deepEqual(c("orders_status_check_v2"), { table: "orders", type: "c" });
  assert.deepEqual(c("order_items_variant_id_fkey"), { table: "order_items", type: "f" });
  assert.equal(m.constraints.has("orders_status_check"), false, "el DROP CONSTRAINT posterior la quita");
  assert.equal(m.mustBeValidated.has("products_cost_price_clp_check"), true);
});

test("diffSchema informa faltantes y restricciones sin validar", () => {
  const expected = extractSchemaManifest(SAMPLE);
  const actual = {
    columns: new Map([
      ["users", new Set(["id", "email", "role", "created_at"])],
      ["orders", new Set(["id", "order_no", "customer_id", "status"])],
    ]),
    indexes: new Set(["idx_users_role"]),
    triggers: new Map([["trg_users_updated_at", { table: "users" }]]),
    functions: new Set(["set_updated_at"]),
    constraints: new Map([
      ["users_pkey", { table: "users", type: "p", validated: true }],
      ["users_email_key", { table: "users", type: "u", validated: true }],
      ["users_role_check", { table: "users", type: "c", validated: true }],
      ["orders_pkey", { table: "orders", type: "p", validated: true }],
      ["orders_order_no_key", { table: "orders", type: "u", validated: true }],
      ["orders_customer_id_fkey", { table: "orders", type: "f", validated: true }],
      ["orders_range_chk", { table: "orders", type: "c", validated: true }],
      ["orders_status_check_v2", { table: "orders", type: "c", validated: false }],
      ["products_cost_price_clp_check", { table: "products", type: "c", validated: false }],
    ]),
  };
  const { missing, warnings } = diffSchema(expected, actual);
  assert.ok(missing.includes("columna users.session_version"));
  assert.ok(missing.includes("tabla recipes"));
  assert.ok(missing.includes("restricción order_items_variant_id_fkey (order_items)"));
  assert.equal(missing.some((m) => m.startsWith("índice")), false);
  assert.ok(warnings.some((w) => w.includes("products_cost_price_clp_check")));
  assert.ok(warnings.some((w) => w.includes("orders_status_check_v2")));
});

test("el esquema canónico real se puede describir completo", () => {
  const { buildMigrationStatements } = require("../src/migrations/complete");
  const statements = buildMigrationStatements();
  const m = extractSchemaManifest(statements);
  for (const table of [
    "users", "products", "customers", "orders", "order_items", "product_images", "product_variants",
    "supplies", "providers", "expense_records", "expense_record_items", "kitchen_equipment", "recipes",
    "recipe_components", "recipe_items", "cake_config_category", "cake_config_option", "cake_orders",
    "product_toppings", "system_config", "hero_slides", "platform_fee_tiers", "platform_fee_charges",
    "schema_migration_state",
  ]) {
    assert.ok(m.tables.has(table), `falta la tabla ${table} en el manifiesto`);
  }
  assert.ok(m.tables.get("users").has("session_version"));
  assert.ok(m.tables.get("orders").has("order_code"));
  // La v3 (vocabulario canónico) reemplazó a la v2 en el mismo bloque.
  assert.ok(m.constraints.has("orders_status_check_v3"));
  assert.equal(m.constraints.has("orders_status_check_v2"), false);
  assert.equal(m.constraints.has("orders_status_check"), false);
  assert.ok(m.triggers.has("trg_update_stock_variants_insert_update"));
  assert.ok(m.functions.has("update_product_stock_from_variants"));
  // Toda sentencia tiene una etiqueta reconocible (nada cae en "statement").
  for (const sql of statements) {
    assert.notEqual(describeStatement(sql), "statement", sql.slice(0, 80));
  }
});
